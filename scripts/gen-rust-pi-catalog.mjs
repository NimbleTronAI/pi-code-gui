// Measure the pinned rust-pi's OWN model catalog, black-box, and write it to
// src/rust-pi-catalog.generated.json. The Rust models.json merge (src/rust-models.ts) reads it to
// decide, per model, whether an override ADJUSTS a model rust-pi already lists or would CREATE one
// it lacks — and a created model is allowed only on the connection Pi itself uses (C29).
//
//   node scripts/gen-rust-pi-catalog.mjs <path to the pinned rust-pi binary>
//
// Run it after bumping src/rust-pi-version.json; a unit test fails while the two disagree.
//
// Clean room (AGENTS.md §"pi clean-room"): this only DRIVES the binary and reads its stdout —
// `--version`, `--list-providers`, and the RPC `get_available_models` — in a throwaway HOME and
// agent dir, with PI_OFFLINE=1 and a dummy value for every provider key so every provider lists.
// No prompt is sent and nothing leaves the machine.
//
// For each provider of the bundled Pi catalog it records:
//   ids       every model id rust-pi lists for it with no models.json of ours
//   newModel  the (api, baseUrl) rust-pi gives a model it does NOT list — measured by writing one
//             override for a made-up id and reading back the connection rust-pi created it on
// A provider rust-pi does not list at all is left out.
import { spawn, execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const bin = process.argv[2];
if (!bin) { console.error("usage: node scripts/gen-rust-pi-catalog.mjs <rust-pi binary>"); process.exit(2); }
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(root, "src", "rust-pi-catalog.generated.json");
const SENTINEL = "pi-code-gui-new-model-probe";
const floor = JSON.parse(readFileSync(join(root, "src", "model-registry.generated.json"), "utf8"));

const scratch = mkdtempSync(join(tmpdir(), "rust-pi-catalog-"));
const home = join(scratch, "home"), agent = join(scratch, "agent"), cwd = join(scratch, "cwd");
for (const d of [home, agent, cwd]) { mkdirSync(d, { recursive: true }); }
const baseEnv = { PATH: process.env.PATH ?? "/usr/bin:/bin", HOME: home, PI_CODING_AGENT_DIR: agent, PI_OFFLINE: "1" };

try {
  const version = /\bpi (\d+\.\d+\.\d+)/.exec(execFileSync(bin, ["--version"], { env: baseEnv, cwd, encoding: "utf8" }))?.[1];
  if (!version) { throw new Error("could not read the binary's version"); }
  const listing = execFileSync(bin, ["--list-providers"], { env: baseEnv, cwd, encoding: "utf8" });
  const env = { ...baseEnv };
  for (const k of new Set(listing.match(/\b[A-Z][A-Z0-9_]*_(?:API_KEY|TOKEN|KEY)\b/g) ?? [])) { env[k] = "dummy-local-only"; }

  const pids = Object.keys(floor.providers);
  writeFileSync(join(agent, "models.json"), JSON.stringify({
    providers: Object.fromEntries(pids.map((p) => [p, { modelOverrides: { [SENTINEL]: { name: SENTINEL, contextWindow: 1000 } } }])),
  }));
  const models = await availableModels(bin, env, cwd, join(scratch, "sessions"));

  const providers = {};
  for (const p of pids) {
    const listed = models.filter((m) => m.provider === p);
    const probe = listed.find((m) => m.id === SENTINEL);
    if (!probe) { continue; }
    providers[p] = {
      newModel: { api: probe.api, baseUrl: probe.baseUrl },
      ids: listed.filter((m) => m.id !== SENTINEL).map((m) => m.id).sort(),
    };
  }
  const doc = {
    _comment: "GENERATED by scripts/gen-rust-pi-catalog.mjs from the pinned rust-pi binary (black-box). Do not edit by hand.",
    rustPi: version,
    providers,
  };
  writeFileSync(OUT, JSON.stringify(doc, null, 2) + "\n");
  console.log(`rust-pi ${version}: ${Object.keys(providers).length} of ${pids.length} Pi providers, ${Object.values(providers).reduce((a, p) => a + p.ids.length, 0)} own ids -> ${OUT}`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

/** Spawn `--mode rpc`, ask get_available_models once, stop the process. */
function availableModels(binary, env, dir, sessions) {
  return new Promise((resolve, reject) => {
    const p = spawn(binary, ["--mode", "rpc", "--session-dir", sessions, "--no-extensions", "--no-context-files"], { cwd: dir, env, stdio: ["pipe", "pipe", "pipe"] });
    let buf = "", err = "";
    const timer = setTimeout(() => { p.kill("SIGTERM"); reject(new Error(`no get_available_models reply within 20 s; stderr: ${err.slice(0, 400)}`)); }, 20_000);
    p.stderr.on("data", (d) => { err += d; });
    p.stdout.on("data", (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf("\n")) >= 0) {
        const line = buf.slice(0, i); buf = buf.slice(i + 1);
        let j; try { j = JSON.parse(line); } catch { continue; }
        if (j.type === "response" && j.id === "models") {
          clearTimeout(timer); p.kill("SIGTERM");
          if (!j.success) { reject(new Error(`get_available_models failed: ${line.slice(0, 400)}`)); return; }
          resolve(j.data?.models ?? []);
        }
      }
    });
    p.on("error", (e) => { clearTimeout(timer); reject(e); });
    p.stdin.write(JSON.stringify({ id: "models", type: "get_available_models" }) + "\n");
  });
}
